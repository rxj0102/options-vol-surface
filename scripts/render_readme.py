"""Render the README calibration table from outputs/calibration_results.csv.

    python scripts/render_readme.py          # rewrite the block in README.md
    python scripts/render_readme.py --check  # exit 1 if README.md is out of date
"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
START = "<!-- results:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- results:end -->"


def render() -> str:
    r = pd.read_csv(ROOT / "outputs" / "calibration_results.csv").iloc[0]
    feller = 2 * r.kappa * r.theta / r.sigma_v ** 2
    o = ["| Parameter | Value |", "|-----------|-------|",
         f"| v0 (initial var) | {r.v0:.4f} |", f"| kappa (mean reversion) | {r.kappa:.4f} |",
         f"| theta (long-run var) | {r.theta:.4f} |", f"| sigma_v (vol-of-vol) | {r.sigma_v:.4f} |",
         f"| rho (correlation) | {r.rho:.4f} |", f"| **Calibration RMSE (implied vol)** | **{r.rmse:.4f}** |",
         f"| Optimizer converged | {bool(r.converged)} |", "",
         f"Feller ratio 2 kappa theta / sigma_v^2 = {feller:.3f}."]
    flags = []
    if abs(r.rho) > 0.95:
        flags.append(f"rho = {r.rho:.3f} is close to -1")
    if abs(feller - 1) < 0.01:
        flags.append("the soft Feller penalty in `heston_rmse` is binding (ratio about 1)")
    if flags:
        o.append("This fit sits on a boundary: " + "; ".join(flags) + ". With at most 60 near-the-money quotes the "
                 "parameters are weakly identified, so treat them as a description of one snapshot rather than stable estimates.")
    return "\n".join(o)


def main():
    readme = ROOT / "README.md"
    text = readme.read_text()
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    new = pre + START + "\n" + render() + "\n" + END + post
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README calibration table is out of date. Run: python scripts/render_readme.py")
        print("README calibration table matches outputs/")
        return
    readme.write_text(new)
    print(render())


if __name__ == "__main__":
    main()

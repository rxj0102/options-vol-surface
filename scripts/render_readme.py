"""Fill the generated blocks in README.md from results/metrics.json.

    python scripts/render_readme.py          # rewrite the blocks
    python scripts/render_readme.py --check  # exit 1 if README.md is out of date

Wording that depends on a result (significant or not, larger or smaller) is
chosen from the numbers, so the prose cannot drift from the results.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = "(generated by scripts/render_readme.py, do not edit by hand)"


def f(x, d=1):
    return f"{x:,.{d}f}"


def pct(x, d=0):
    return f"{100 * x:.{d}f}%"


def sig(p):
    return "significant" if p < 0.05 else "not significant"


def vrp_block(v):
    assert v["vrp_vol_points_mean"] > 0, "the README frames VIX as above realized vol"
    lv, lg, lt = (v["loss"][k] for k in ("implied", "garch", "trailing"))
    dm = v["diebold_mariano"]
    mz = v["mincer_zarnowitz"]
    w = v["worst_blocks"]
    better_mse = "VIX" if lv["mse"] < lg["mse"] else "GARCH"
    better_ql = "VIX" if lv["qlike"] < lg["qlike"] else "GARCH"
    o = [
        f"{v['n_blocks']} non-overlapping 21 trading day blocks, {v['first_block'][:4]} to {v['last_block'][:4]}. "
        "Forecasts are fixed at the close of the first day; realized variance uses the next 21 daily returns.",
        "",
        "**The premium.** "
        f"VIX averaged {f(v['mean_vix'])} and the volatility that followed averaged {f(v['mean_realized_vol'])}. "
        f"VIX was above the realized volatility of its block in {pct(v['share_implied_above_realized'])} of blocks, "
        f"by {f(v['vrp_vol_points_mean'])} vol points on average (median {f(v['vrp_vol_points_median'])}, "
        f"Newey-West t {f(v['vrp_vol_points_t'])}).",
        "",
        "**Selling it.** Selling one unit of 21 day variance at VIX squared each block earned "
        f"{f(v['short_var_mean'], 0)} variance points (vol points squared) a block (t {f(v['short_var_t'])}), "
        f"a Sharpe ratio of {f(v['short_var_sharpe_annual'], 2)} a year with skewness {f(v['short_var_skew'])}. "
        f"The three worst blocks ({', '.join(x['date'][:7] for x in w)}) together lost an amount equal to "
        f"{pct(v['short_var_share_of_total_lost_in_worst3'])} of the strategy's net profit over the whole sample. "
        f"The {w[1]['date'][:7]} block started with VIX at {f(w[1]['vix'])}; realized volatility over the next month was "
        f"{f(w[1]['realized_vol'])}.",
        "",
        "**Forecasting.** Realized variance compared with each forecast:",
        "",
        "| Forecast | Mean forecast vol | MSE (x 1e-4) | QLIKE | Mincer-Zarnowitz slope | R2 |",
        "|---|---|---|---|---|---|",
    ]
    for name, k in (("VIX squared", "implied"), ("GARCH(1,1), refit yearly", "garch"), ("Trailing 21 day realized", "trailing")):
        L, M = v["loss"][k], mz[k]
        o.append(f"| {name} | {f(L['mean_forecast_vol'])} | {f(L['mse'], 2)} | {f(L['qlike'], 3)} | "
                 f"{f(M['slope'], 2)} (se {f(M['slope_se'], 2)}) | {f(M['r2'], 2)} |")
    e, le = mz["encompassing"], mz["log_encompassing"]
    o += [
        "",
        (f"{better_mse} has the lower MSE and QLIKE" if better_mse == better_ql else
         f"{better_mse} has the lower MSE and {better_ql} the lower QLIKE") + ", but neither difference is significant "
        f"(Diebold-Mariano p {f(dm['implied_vs_garch_mse']['p'], 2)} and {f(dm['implied_vs_garch_qlike']['p'], 2)}). "
        if dm["implied_vs_garch_mse"]["p"] >= 0.05 and dm["implied_vs_garch_qlike"]["p"] >= 0.05 else
        f"VIX against GARCH: Diebold-Mariano p {f(dm['implied_vs_garch_mse']['p'], 2)} (MSE) and "
        f"{f(dm['implied_vs_garch_qlike']['p'], 2)} (QLIKE). ",
    ]
    o[-1] += (f"Both beat the trailing realized variance on QLIKE (p {f(dm['implied_vs_trailing_qlike']['p'], 3)} for VIX, "
              f"{f(dm['garch_vs_trailing_qlike']['p'], 4)} for GARCH). "
              f"So VIX is too high on average but not a worse forecast than a GARCH model: the bias is a level shift. "
              f"In logs, regressing realized on both forecasts gives VIX a weight of {f(le['b_implied'], 2)} "
              f"(t {f(le['t_implied'])}) and GARCH {f(le['b_garch'], 2)} (t {f(le['t_garch'])}); "
              f"in levels, {f(e['b_implied'], 2)} (t {f(e['t_implied'])}) and {f(e['b_garch'], 2)} (t {f(e['t_garch'])}). "
              "Option prices carry information about future volatility that past returns do not.")
    assert le["t_implied"] > 2, "the README says VIX carries information beyond GARCH"
    assert dm["implied_vs_garch_mse"]["p"] >= 0.05 and dm["implied_vs_garch_qlike"]["p"] >= 0.05, \
        "the README says VIX is not a worse forecast than GARCH"
    assert abs(mz["log_implied"]["slope"] - 1) < 2 * mz["log_implied"]["slope_se"], \
        "the README calls the VIX bias a level shift"
    return "\n".join(o)


def surface_block(s):
    h = s["heston"]
    per = sorted(s["per_expiry"], key=lambda r: r["T"])
    o = [
        f"Snapshot `{s['snapshot']}`, pulled {s['pulled_utc']} UTC with SPY at {s['spot']}. "
        f"{s['n_quotes_used']} out-of-the-money quotes across {s['n_expiries']} expiries survive the filters "
        f"(both sides quoted, spread under half the mid, mid at least 5 cents, between the 2 delta put and call), out of {s['n_quotes_raw']} raw quotes.",
        "",
        "| Expiry | Days | Quotes | ATM vol | 25d risk reversal | 25d butterfly | SVI RMSE | Heston RMSE |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in per:
        atm = f"{100 * r['atm']:.1f}" if "atm" in r else ""
        rr = f"{100 * r['rr25']:.1f}" if "rr25" in r else ""
        bf = f"{100 * r['bf25']:.2f}" if "bf25" in r else ""
        o.append(f"| {r['expiry']} | {365 * r['T']:.0f} | {r['n']} | {atm} | {rr} | {bf} | "
                 f"{r['svi_rmse']:.2f} | {r['heston_rmse']:.2f} |")
    o += [
        "",
        "Vols and RMSEs in vol points. Risk reversal is the 25 delta call vol minus the 25 delta put vol.",
        "",
        f"One Heston parameter set for the whole surface: v0 {h['v0']:.4f}, kappa {h['kappa']:.2f}, "
        f"theta {h['theta']:.4f}, sigma_v {h['sigma_v']:.2f}, rho {h['rho']:.2f}. "
        f"Feller ratio 2 kappa theta / sigma_v^2 = {h['feller_ratio']:.2f}"
        + (" (below 1, so the variance process can reach zero, which is typical of fits to index smiles). "
           if h["feller_ratio"] < 1 else ". ")
        + f"Overall RMSE {s['heston_rmse']:.2f} vol points against {s['svi_rmse']:.2f} for SVI fitted expiry by expiry; "
        f"{s['heston_rmse_short']:.2f} on expiries under 55 days and {s['heston_rmse_long']:.2f} beyond. "
        + ("One set of five parameters has to produce every maturity's smile at once, and its errors are largest in the "
           "shortest expiries, where the smile is steepest in strike. SVI, with five parameters for each expiry, fits "
           "every slice to within a fraction of a vol point."
           if s["heston_rmse_short"] > s["heston_rmse_long"] and max(r["svi_rmse"] for r in per) < 1 else ""),
        "",
        f"SVI static arbitrage checks: {s['svi_butterfly_violations']} of {s['n_expiries']} slices have butterfly "
        f"arbitrage on their quoted range (minimum g(k) {s['svi_butterfly_min_g']:.3f}); "
        f"{s['svi_calendar_violations']} calendar violations on the log-moneyness range all expiries share "
        f"({s['svi_calendar_k_range'][0]:.2f} to {s['svi_calendar_k_range'][1]:.2f}).",
    ]
    return "\n".join(o)


def density_block(s):
    per = sorted(s["per_expiry"], key=lambda r: r["T"])
    assert s["svi_wing_slope_max"] < 2, "Lee's bound: wing slopes above 2 give an infinite mean"
    o = [
        "Each SVI slice implies a density for the price at expiry (the second strike derivative of call prices). "
        f"Every density integrates to 1 within {s['density_max_mass_error']:.1e}, and every slice respects Roger Lee's "
        f"moment bound (steepest wing slope {s['svi_wing_slope_max']:.2f} against a limit of 2), so each has a finite mean. "
        f"As a model-free check, the price of a tight put spread around 90% of the forward is the market's own "
        f"P(S_T below that strike); across {s['put_spread_n']} expiries it differs from the SVI density's value by at most "
        f"{100 * s['put_spread_max_gap']:.1f} percentage points. "
        "The columns compare the probability of a fall below 90% or 80% of the forward with a lognormal at the same "
        "expiry's at-the-money total variance, which is what a flat smile would say.",
        "",
        "| Expiry | Days | P(below 90% of F) | Lognormal at ATM vol | P(below 80% of F) | Lognormal at ATM vol | Mass inside quoted strikes |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in per:
        d = r["density"]
        o.append(f"| {r['expiry']} | {365 * r['T']:.0f} | {pct(d['p_below_90'], 1)} | {pct(d['p_below_90_atm_lognormal'], 1)} | "
                 f"{pct(d['p_below_80'], 2)} | {pct(d['p_below_80_atm_lognormal'], 2)} | {pct(d['mass_in_quoted_range'], 1)} |")
    o += ["", "The last column is the share of each density that sits between the lowest and highest quoted strikes; "
          "the rest comes from SVI's straight-line wings, so tail probabilities beyond the quotes are extrapolation."]
    return "\n".join(o)


def fill(text, name, body):
    start, end = f"<!-- {name}:start {GEN} -->", f"<!-- {name}:end -->"
    pre, rest = text.split(start, 1)
    _, post = rest.split(end, 1)
    return pre + start + "\n" + body + "\n" + end + post


def main():
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(text, "vrp", vrp_block(m["vrp"]))
    new = fill(new, "surface", surface_block(m["surface"]))
    new = fill(new, "density", density_block(m["surface"]))
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README.md is out of date. Run: python scripts/render_readme.py")
        print("README matches results/metrics.json")
        return
    readme.write_text(new)


if __name__ == "__main__":
    main()
